/* ==========================================================
   ГЛАВНАЯ ФУНКЦИЯ ГЕНЕРАЦИИ
   Аргументы:
     pool        — пул pg
     ownerId     — id админа (владелец задач)
     N           — сколько вариаций генерировать
     prototypeId — (опционально) id прототипа для привязки
   ========================================================== */
async function generateTasks(pool, ownerId, N, prototypeId) {
  N = Math.max(1, parseInt(N) || 20);

  /* Если задан прототип — берём его номер, тему, сложность */
  let allowedNumbers = null;
  let protoRow = null;

  if (prototypeId) {
    const r = await pool.query(
      'SELECT id, exam_task_number, topic, difficulty FROM task_bank WHERE id=$1 AND is_prototype=true',
      [prototypeId]);
    protoRow = r.rows[0] || null;
    if (!protoRow) throw new Error('Прототип не найден: ' + prototypeId);
    allowedNumbers = [protoRow.exam_task_number];
  }

  /* Считаем следующий variant_index */
  let variantStart = 1;
  if (prototypeId) {
    const vc = await pool.query(
      'SELECT COUNT(*)::int AS n FROM task_bank WHERE prototype_id=$1', [prototypeId]);
    variantStart = vc.rows[0].n + 1;
  }

  const seen = new Set();
  const result = { added: 0, failed: 0, byNumber: {} };

  /* Фильтр шаблонов по номеру задания */
  const templates = allowedNumbers
    ? TEMPLATES.filter(t => allowedNumbers.includes(t.n))
    : TEMPLATES;

  if (!templates.length) {
    throw new Error('Нет шаблонов для номера ' + (allowedNumbers ? allowedNumbers[0] : '?'));
  }

  for (const t of templates) {
    let made = 0, tries = 0;
    const MAX_TRIES = Math.max(N * 25, 60);

    while (made < N && tries < MAX_TRIES) {
      tries++;
      let task;
      try { task = t.gen(); } catch (e) { continue; }
      if (!task || !task.stmt || !task.ans) continue;

      /* Ответ должен быть числом или десятичной дробью */
      if (!/^-?\d+(\.\d+)?$/.test(String(task.ans).trim())) continue;

      if (seen.has(task.stmt)) continue;
      seen.add(task.stmt);

      /* Вклейка SVG-чертежа, если он есть */
      let finalStatement = task.stmt;
      if (task.svg) {
        finalStatement = '<div class="task-figure">' + task.svg + '</div>\n' + finalStatement;
      }

      const finalTopic = (protoRow && protoRow.topic) ? protoRow.topic : t.topic;
      const finalDiff  = (protoRow && protoRow.difficulty) ? protoRow.difficulty : t.d;
      const vIdx = prototypeId ? (variantStart + made) : null;

      try {
        await pool.query(
          `INSERT INTO task_bank
             (id, owner_id, exam_type, exam_task_number, topic, difficulty,
              statement, type, answer, tolerance, options, correct_index,
              points, is_public, is_prototype, prototype_id, variant_index,
              solution, figure_svg, created_at)
           VALUES ($1,$2,'profile',$3,$4,$5,$6,'input',$7,$8,NULL,NULL,1,true,false,$9,$10,NULL,NULL,$11)`,
          [uid(), ownerId, t.n, finalTopic, finalDiff,
           finalStatement, String(task.ans),
           typeof task.tol === 'number' ? task.tol : 1e-6,
           prototypeId || null,
           vIdx,
           Date.now()]
        );
        result.added++;
        result.byNumber[t.n] = (result.byNumber[t.n] || 0) + 1;
        made++;
      } catch (e) {
        result.failed++;
      }
    }
  }
  return result;
}

